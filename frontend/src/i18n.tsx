const dictionaries: Record<Lang, Record<Key, string>> = { en, fr };

let activeLang: Lang = "en";

function readStoredLang(): Lang {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === "fr" || stored === "en") return stored;
  } catch {
    /* ignore */
  }
  if (typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("fr")) return "fr";
  return "en";
}

export function getLang() {
  return activeLang;
}

export function localeFor(lang: Lang = activeLang) {
  return lang === "fr" ? "fr-FR" : "en-GB";
}

export function money(value: string | number) {
  return `${Number(value || 0).toLocaleString(localeFor(), { minimumFractionDigits: 2 })} MAD`;
}

export function date(value: string) {
  return new Intl.DateTimeFormat(localeFor(), {
    day: "2-digit",
    month: "short",
    year: "numeric",
  }).format(new Date(value));
}

export function clock(value: string) {
  return new Intl.DateTimeFormat(localeFor(), {
    hour: "2-digit",
    minute: "2-digit",
  }).format(new Date(value));
}

export function todayLabel(compact = false) {
  return new Intl.DateTimeFormat(localeFor(), compact
    ? { weekday: "short", day: "numeric", month: "short" }
    : { weekday: "long", day: "2-digit", month: "long", year: "numeric" }).format(new Date());
}

export function monthLabel(year: number, month: number) {
  return new Date(year, month - 1, 1).toLocaleString(localeFor(), { month: "long", year: "numeric" });
}

export function translate(key: Key, vars?: Record<string, string | number>, lang: Lang = activeLang) {
  let text = dictionaries[lang][key] || dictionaries.en[key] || key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function statusLabel(value: string, lang: Lang = activeLang) {
  const key = `status.${value}` as Key;
  if (key in dictionaries.en) return translate(key, undefined, lang);
  return value.replaceAll("_", " ");
}

type I18nValue = {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: Key, vars?: Record<string, string | number>) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const initial = readStoredLang();
    activeLang = initial;
    if (typeof document !== "undefined") document.documentElement.lang = initial;
    return initial;
  });

  const setLang = (next: Lang) => {
    activeLang = next;
    localStorage.setItem(STORAGE_KEY, next);
    document.documentElement.lang = next;
    setLangState(next);
  };

  const value = useMemo<I18nValue>(
    () => ({
      lang,
      setLang,
      t: (key, vars) => translate(key, vars, lang),
    }),
    [lang],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useLang() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useLang must be used inside LanguageProvider");
  return ctx;
}

export function LanguageSwitch({ compact = false }: { compact?: boolean }) {
  const { lang, setLang, t } = useLang();
  return (
    <div className={`lang-switch ${compact ? "compact" : ""}`} role="group" aria-label={t("lang.label")}>
      <button type="button" className={lang === "en" ? "active" : ""} onClick={() => setLang("en")}>
        EN
      </button>
      <button type="button" className={lang === "fr" ? "active" : ""} onClick={() => setLang("fr")}>
        FR
      </button>
    </div>
  );
}
